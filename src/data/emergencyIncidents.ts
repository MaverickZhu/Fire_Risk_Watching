function incidentUnit(
  id: string,
  name: string,
  district: string,
  street: string,
  industry: RiskObject['industry'],
  objectType: string,
  riskLevel: RiskObject['riskLevel'],
  lng: number,
  lat: number,
  signals: string[],
): RiskObject {
  return {
    id,
    name,
    district,
    street,
    industry,
    objectType,
    riskLevel,
    location: { lng, lat },
    signals,
    status: riskLevel === 'critical' ? '处置中' : '预警',
    updatedAt: '实时',
    sourceNote: emergencySourceNote,
    dataConfidence: 'medium',
  }
}

