function force(
  id: string,
  taskId: string,
  name: string,
  forceType: SecurityForcePoint['forceType'],
  district: string,
  address: string,
  lng: number,
  lat: number,
  status: SecurityForcePoint['status'],
  editable: boolean,
  personnel: number,
  vehicles: number,
  equipment: string[],
  commander: string,
  contactChannel: string,
  coverageRadius: number,
  liveStatus: SecurityForcePoint['liveFeed']['status'],
  liveTitle: string,
  snapshotTone: SecurityForcePoint['liveFeed']['snapshotTone'],
): SecurityForcePoint {
  return {
    id,
    taskId,
    name,
    forceType,
    district,
    address,
    location: { lng, lat },
    status,
    editable,
    personnel,
    vehicles,
    equipment,
    commander,
    contactChannel,
    coverageRadius,
    liveFeed: {
      status: liveStatus,
      title: liveTitle,
      snapshotTone,
    },
  }
}
